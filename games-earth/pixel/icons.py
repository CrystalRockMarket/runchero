def validate() -> list[str]:
    """Return a list of problems with the icon set (empty when all is well)."""
    problems: list[str] = []
    for name, rows in ICONS.items():
        if len(rows) != ICON_SIZE:
            problems.append(f"{name}: has {len(rows)} rows, expected {ICON_SIZE}")
        for index, row in enumerate(rows):
            if len(row) != ICON_SIZE:
                problems.append(
                    f"{name}: row {index} has {len(row)} cols, expected {ICON_SIZE}"
                )
            for char in row:
                if char != "." and char not in LEGEND:
                    problems.append(f"{name}: row {index} has unknown char {char!r}")
    return problems


