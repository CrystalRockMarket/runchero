def _row(slug, name, kind, group, subgroup, icon, accent, summary="",
         aliases="", scientific="", keywords="", books=(), featured=0,
         category="", limit=0):
    return {
        "slug": slug,
        "name": name,
        "kind": kind,
        "group_slug": group,
        "group_name": GROUP_TITLES[group],
        "subgroup_slug": subgroup,
        "subgroup_name": subgroup.replace("-", " ").title(),
        "icon": icon,
        "accent": accent,
        "summary": summary,
        "aliases": aliases,
        "scientific": scientific,
        "keywords": keywords,
        "books": list(books),
        "featured": featured,
        "category": category,
        "limit": limit,
    }


def crop(slug, name, group, subgroup, icon="seedling", accent="grass",
         aliases="", scientific="", keywords="", books=(), featured=0,
         summary=""):
    return _row(slug, name, "crop", group, subgroup, icon, accent, summary,
                aliases, scientific, keywords, books, featured)


def animal(slug, name, group, subgroup, icon="cow", accent="tomato2",
           aliases="", scientific="", keywords="", books=(), featured=0,
           summary=""):
    return _row(slug, name, "animal", group, subgroup, icon, accent, summary,
                aliases, scientific, keywords, books, featured)


def topic(slug, name, group, subgroup, icon="notes", accent="sun",
          aliases="", keywords="", books=(), featured=0, summary="",
          category="", limit=0):
    return _row(slug, name, "topic", group, subgroup, icon, accent, summary,
                aliases, "", keywords, books, featured, category, limit)


