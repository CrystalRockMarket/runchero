_LEGEND_CHARS = set(palette.ICON_LEGEND) | {" "}


def validate() -> list[str]:
    """Return a list of problems (rows that are not exactly 16 characters)."""
    problems: list[str] = []
    for name, rows in ICONS.items():
        if len(rows) != ICON_SIZE:
            problems.append(f"{name}: has {len(rows)} rows")
        for index, row in enumerate(rows):
            if len(row) != ICON_SIZE:
                problems.append(f"{name}[{index}]: {len(row)} chars -> {row!r}")
            unknown = set(row) - set(_LEGEND_CHARS)
            if unknown:
                problems.append(f"{name}[{index}]: unknown chars {sorted(unknown)}")
    return problems
