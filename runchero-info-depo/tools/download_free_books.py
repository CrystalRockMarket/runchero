def slugify(title: str) -> str:
    title = re.sub(r"\s+", " ", (title or "")).strip()
    slug = re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")
    return re.sub(r"-{2,}", "-", slug)[:80].strip("-")


def split_fields(value) -> list[str]:
    if isinstance(value, list):
        return [str(v).strip() for v in value if str(v).strip()]
    return [part.strip() for part in (value or "").split(";") if part.strip()]


def normalize(value) -> str:
    if isinstance(value, list):
        return "; ".join(str(v) for v in value)
    return re.sub(r"\s+", " ", str(value or "")).strip()


def fetch_bytes(url: str, timeout: int = 90) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read()


def load_catalog() -> list[dict]:
    if not CATALOG_CACHE.exists():
        CATALOG_CACHE.parent.mkdir(parents=True, exist_ok=True)
        print("fetching the Gutenberg catalogue...", flush=True)
        CATALOG_CACHE.write_bytes(fetch_bytes(CATALOG_URL, timeout=120))
    with gzip.open(CATALOG_CACHE, "rt", encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def topic_for_row(row: dict) -> str | None:
    subjects = split_fields(row.get("Subjects", ""))
    bookshelves = split_fields(row.get("Bookshelves", ""))
    blob = f"{'; '.join(subjects)}; {'; '.join(bookshelves)}".lower()
    title = normalize(row.get("Title", ""))
    if any(bad in blob for bad in BAD) or BAD_TITLE.search(title):
        return None
    best_topic, best_score = None, 0
    for topic, keywords in DEEP_TOPICS.items():
        score = sum(1 for kw in keywords if kw in blob or kw in title.lower())
        if score > best_score:
            best_topic, best_score = topic, score
    if best_topic is not None and best_score >= 2:
        return best_topic
    for topic, keywords in SKELETON_TOPICS.items():
        score = sum(1 for kw in keywords if kw in blob or kw in title.lower())
        if score > best_score:
            best_topic, best_score = topic, score
    if best_topic is not None and best_score >= 2:
        return best_topic
    return None


def gutenberg_candidates(catalog: list[dict], per_topic: int,
                         used_slugs: set[str]) -> list[dict]:
    counts: dict[str, int] = {}
    picked: list[dict] = []
    for row in catalog:
        if row.get("Language") != "en" or row.get("Type") != "Text":
            continue
        topic = topic_for_row(row)
        if topic is None or counts.get(topic, 0) >= per_topic:
            continue
        try:
            gid = int(row["Text#"])
        except (TypeError, ValueError):
            continue
        title = normalize(row.get("Title", ""))
        if not title:
            continue
        slug = slugify(title)
        if not slug or slug in used_slugs:
            continue
        picked.append({
            "source": "gutenberg",
            "identifier": str(gid),
            "topic": topic,
            "title": title,
            "creator": normalize(row.get("Authors", "")) or "Unknown",
            "date": normalize(row.get("Issued", "")),
            "subjects": split_fields(row.get("Subjects", "")),
            "license": "Public domain (Project Gutenberg)",
            "source_url": f"https://www.gutenberg.org/ebooks/{gid}",
        })
        counts[topic] = counts.get(topic, 0) + 1
        used_slugs.add(slug)
    return picked


def date_year(value) -> int | None:
    match = re.search(r"\b(1[0-9]{3}|20[0-2][0-9])\b", normalize(value))
    return int(match.group(1)) if match else None


def ia_accept(topic: str, title: str, info: dict, collections: str) -> bool:
    if any(bad in collections for bad in BAD_COLLECTIONS):
        return False
    if not any(good in collections for good in GOOD_COLLECTIONS):
        return False
    is_catalog = any(bad in collections for bad in CATALOG_COLLECTIONS)
    if is_catalog and topic != "chainsaw":
        return False
    year = date_year(info.get("date"))
    if year is not None and year > 1965:
        return False
    if (year is not None and year > 1930
            and not any(good in collections
                        for good in ("manuals",) + CATALOG_COLLECTIONS)):
        return False
    if year is None and "opensource" in collections:
        return False
    if BAD_TITLE.search(title):
        return False
    if CATALOG_TITLE.search(title) and not is_catalog:
        return False
    subjects = split_fields(info.get("subject"))
    title_l = title.lower()
    subject_l = " ".join(subject.lower() for subject in subjects)
    keywords = DEEP_TOPICS[topic]
    title_hits = sum(1 for keyword in keywords if keyword in title_l)
    subject_hits = sum(1 for keyword in keywords if keyword in subject_l)
    if title_hits == 0 and subject_hits < 2:
        return False
    if topic == "ky-crops" and subject_hits == 0:
        return False
    if (topic == "animal-husbandry" and subject_hits == 0
            and "manuals" not in collections):
        return False
    if topic == "chainsaw" and subject_hits == 0 and not is_catalog:
        return False
    if any(bad in subject_l for bad in
           ("cookery", "cooking", "recipes", "postcards", "photographs",
            "periodicals", "newspapers", "fiction", "juvenile", "cowboys")):
        return False
    if topic == "ky-crops" and "kentucky" in title_l:
        crop_words = [keyword for keyword in keywords
                      if keyword not in ("kentucky", "bluegrass")]
        if not any(keyword in title_l for keyword in crop_words):
            return False
    return True


def ia_candidates(per_topic: int, used_slugs: set[str],
                  max_file_mb: int) -> list[dict]:
    picked: list[dict] = []
    seen: set[str] = set()
    for topic, clause in IA_QUERIES.items():
        query = (
            f"{clause} AND mediatype:texts AND language:eng "
            "AND licenseurl:*publicdomain*"
        )
        params = [
            ("q", query),
            ("fl", "identifier,title,creator,date,licenseurl,collection,subject"),
            ("rows", str(max(per_topic * 4, 40))),
            ("output", "json"),
        ]
        url = f"{IA_SEARCH}?{urllib.parse.urlencode(params)}"
        try:
            data = json.loads(fetch_bytes(url, timeout=60).decode("utf-8", "replace"))
        except Exception as error:  # noqa: BLE001
            print(f"  IA search failed for {topic}: {error}", flush=True)
            continue
        docs = data.get("response", {}).get("docs", [])
        count = 0
        for doc in docs:
            if count >= per_topic:
                break
            ident = normalize(doc.get("identifier"))
            title = normalize(doc.get("title"))
            if not ident or not title or ident in seen or BAD_TITLE.search(title):
                continue
            seen.add(ident)
            try:
                meta = json.loads(
                    fetch_bytes(IA_METADATA.format(identifier=ident),
                                timeout=45).decode("utf-8", "replace")
                )
            except Exception:  # noqa: BLE001
                continue
            info = meta.get("metadata", {}) or {}
            collections = " ".join(split_fields(info.get("collection")))
            license_url = normalize(info.get("licenseurl"))
            rights = normalize(info.get("rights")).lower()
            if "publicdomain" not in license_url.lower() and "public domain" not in rights:
                continue
            title = normalize(info.get("title")) or title
            if not ia_accept(topic, title, info, collections):
                continue
            slug = slugify(title)
            if not slug or slug in used_slugs:
                continue
            files = choose_files(meta.get("files", []) or [], max_file_mb)
            if not files:
                continue
            used_slugs.add(slug)
            picked.append({
                "source": "internetarchive",
                "identifier": ident,
                "topic": topic,
                "title": title,
                "creator": normalize(info.get("creator")) or "Unknown",
                "date": normalize(info.get("date")),
                "subjects": split_fields(info.get("subject")),
                "collections": split_fields(info.get("collection")),
                "license": license_url or normalize(info.get("rights")),
                "source_url": f"https://archive.org/details/{ident}",
                "files": files,
            })
            count += 1
    return picked


def choose_files(files: list[dict], max_file_mb: int) -> list[dict]:
    max_bytes = max_file_mb * 1024 * 1024
    texts, pdfs = [], []
    for item in files:
        name = item.get("name", "")
        try:
            size = int(item.get("size") or 0)
        except (TypeError, ValueError):
            size = 0
        if not name:
            continue
        if name.endswith("_djvu.txt"):
            texts.append((name, size))
        elif name.endswith(".txt") and not name.endswith(("_meta.txt", "_files.xml")):
            texts.append((name, size))
        elif name.endswith("_text.pdf"):
            pdfs.append((name, size))
        elif name.endswith(".pdf"):
            pdfs.append((name, size))
    chosen = []
    if texts:
        name, size = min(texts, key=lambda item: item[1] or 10**15)
        chosen.append({"filename": name, "size": size, "kind": "text"})
    if pdfs:
        affordable = [item for item in pdfs if not item[1] or item[1] <= max_bytes]
        if affordable:
            name, size = min(affordable, key=lambda item: item[1] or 10**15)
            chosen.append({"filename": name, "size": size, "kind": "pdf"})
    return chosen


class Budget:
    def __init__(self, limit: int, used: int):
        self.limit = limit
        self.used = used
        self.lock = threading.Lock()

    def reserve(self, size: int) -> bool:
        with self.lock:
            if self.used + size > self.limit:
                return False
            self.used += size
            return True

    def adjust(self, reserved: int, actual: int) -> bool:
        with self.lock:
            self.used += actual - reserved
            return self.used <= self.limit


class Manifest:
    def __init__(self, path: Path):
        self.path = path
        self.lock = threading.Lock()
        self.records: list[dict] = []
        if path.exists():
            for line in path.read_text(encoding="utf-8").splitlines():
                if line.strip():
                    try:
                        self.records.append(json.loads(line))
                    except json.JSONDecodeError:
                        pass

    def keys(self) -> set[tuple[str, str]]:
        return {(r.get("source", ""), str(r.get("identifier", "")))
                for r in self.records}

    def file_paths(self) -> set[str]:
        out = set()
        for record in self.records:
            for item in record.get("files", []):
                out.add(item.get("path", ""))
        return out

    def append(self, record: dict) -> None:
        with self.lock:
            self.records.append(record)
            with self.path.open("a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")
                handle.flush()


def unique_slug(base: str, used: set[str], source: str) -> str:
    if base not in used:
        used.add(base)
        return base
    suffix = "g" if source == "gutenberg" else "ia"
    candidate = f"{base}-{suffix}"
    number = 2
    while candidate in used:
        candidate = f"{base}-{suffix}{number}"
        number += 1
    used.add(candidate)
    return candidate


def download_stream(url: str, target: Path, max_bytes: int,
                    timeout: int = 120) -> tuple[int, str]:
    target.parent.mkdir(parents=True, exist_ok=True)
    part = target.with_suffix(target.suffix + ".part")
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    digest = hashlib.sha256()
    size = 0
    with urllib.request.urlopen(request, timeout=timeout) as response:
        length = response.headers.get("Content-Length")
        if length and int(length) > max_bytes:
            raise RuntimeError(f"file too large: {length} bytes")
        with part.open("wb") as handle:
            while True:
                chunk = response.read(1024 * 256)
                if not chunk:
                    break
                size += len(chunk)
                if size > max_bytes:
                    raise RuntimeError(f"file exceeded limit: {size} bytes")
                digest.update(chunk)
                handle.write(chunk)
    if size == 0:
        part.unlink(missing_ok=True)
        raise RuntimeError("empty file")
    part.replace(target)
    return size, digest.hexdigest()


def download_item(item: dict, budget: Budget, manifest: Manifest,
                  max_file_mb: int) -> dict:
    slug = item["slug"]
    chosen = item.get("files") or []
    if item["source"] == "gutenberg":
        chosen = [
            {"filename": TEXT_URL.format(id=item["identifier"]),
             "size": 8 * 1024 * 1024, "kind": "text"},
            {"filename": ALT_URL.format(id=item["identifier"]),
             "size": 8 * 1024 * 1024, "kind": "text"},
        ]
    estimate = sum(int(f.get("size") or 0) for f in chosen) or 8 * 1024 * 1024
    if not budget.reserve(estimate):
        raise RuntimeError("budget exhausted")
    reserved = estimate
    actual = 0
    settled = False
    files: list[dict] = []
    errors: list[str] = []
    try:
        if item["source"] == "gutenberg":
            target = ARCHIVE / f"{slug}.txt"
            if target.exists() and target.stat().st_size > 0:
                data = target.read_bytes()
                files.append({"path": f"books/{target.name}", "bytes": len(data),
                              "sha256": hashlib.sha256(data).hexdigest(),
                              "source_url": item["source_url"], "kind": "text"})
                actual = len(data)
            else:
                for template in (TEXT_URL, ALT_URL):
                    url = template.format(id=item["identifier"])
                    try:
                        size, digest = download_stream(
                            url, target, max_file_mb * 1024 * 1024)
                        files.append({"path": f"books/{target.name}", "bytes": size,
                                      "sha256": digest, "source_url": url,
                                      "kind": "text"})
                        actual = size
                        break
                    except Exception as error:  # noqa: BLE001
                        errors.append(f"{url}: {error}")
                if not files:
                    raise RuntimeError("; ".join(errors[-2:]))
        else:
            for file_info in chosen:
                filename = file_info["filename"]
                kind = file_info["kind"]
                if kind == "pdf":
                    target = PDF_DIR / f"{slug}.pdf"
                else:
                    target = ARCHIVE / f"{slug}.txt"
                if target.exists() and target.stat().st_size > 0:
                    data = target.read_bytes()
                    files.append({"path": f"books/{target.name}", "bytes": len(data),
                                  "sha256": hashlib.sha256(data).hexdigest(),
                                  "source_url": item["source_url"], "kind": kind})
                    actual += len(data)
                    continue
                url = IA_DOWNLOAD.format(
                    identifier=item["identifier"],
                    filename=urllib.parse.quote(filename, safe=""),
                )
                try:
                    size, digest = download_stream(
                        url, target, max_file_mb * 1024 * 1024)
                except Exception as error:  # noqa: BLE001
                    errors.append(f"{url}: {error}")
                    continue
                rel = (f"books/pdfs/{target.name}" if kind == "pdf"
                       else f"books/{target.name}")
                files.append({"path": rel, "bytes": size, "sha256": digest,
                              "source_url": url, "kind": kind})
                actual += size
        if not files:
            raise RuntimeError("; ".join(errors[-3:]) or "no files downloaded")
        ok = budget.adjust(reserved, actual)
        settled = True
        if not ok:
            for file_info in files:
                path = (PDF_DIR if file_info["path"].endswith(".pdf")
                        else ARCHIVE) / Path(file_info["path"]).name
                path.unlink(missing_ok=True)
            raise RuntimeError("budget exceeded after download")
        record = {k: v for k, v in item.items() if k != "files"}
        record["slug"] = slug
        record["files"] = files
        record["errors"] = errors
        record["downloaded_at"] = datetime.now(timezone.utc).isoformat()
        manifest.append(record)
        return record
    except Exception:
        if not settled:
            budget.adjust(reserved, actual)
        raise


def archive_bytes() -> int:
    total = 0
    for path in ARCHIVE.glob("*.txt"):
        total += path.stat().st_size
    for path in PDF_DIR.glob("*.pdf"):
        total += path.stat().st_size
    return total


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Download public-domain farm books")
    parser.add_argument("--budget-gb", type=float, default=DEFAULT_BUDGET_GB)
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--per-topic", type=int, default=40,
                        help="max new Gutenberg books per topic")
    parser.add_argument("--ia-per-topic", type=int, default=15,
                        help="max new Internet Archive items per topic")
    parser.add_argument("--max-file-mb", type=int, default=MAX_FILE_MB)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args(argv)

    config.ensure_dirs()
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    LOCK.parent.mkdir(parents=True, exist_ok=True)
    lock_handle = LOCK.open("w")
    try:
        fcntl.flock(lock_handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print("another download is already running", file=sys.stderr)
        return 1

    manifest = Manifest(MANIFEST)
    done_keys = manifest.keys()
    done_files = manifest.file_paths()
    used_slugs = {p.stem for p in ARCHIVE.glob("*.txt")}
    used_slugs.update(p.stem for p in PDF_DIR.glob("*.pdf"))
    used_slugs.update(Path(p).stem for p in done_files if p)

    catalog = load_catalog()
    print("selecting Project Gutenberg books...", flush=True)
    guten = gutenberg_candidates(catalog, args.per_topic, used_slugs)
    print(f"  {len(guten)} new Gutenberg candidates", flush=True)

    print("searching Internet Archive...", flush=True)
    ia_items = ia_candidates(args.ia_per_topic, used_slugs, args.max_file_mb)
    print(f"  {len(ia_items)} new Internet Archive candidates", flush=True)

    entries = [item for item in [*guten, *ia_items]
               if (item["source"], item["identifier"]) not in done_keys]
    for item in entries:
        item["slug"] = unique_slug(slugify(item["title"]), used_slugs,
                                   item["source"])

    limit = int(args.budget_gb * 1024 * 1024 * 1024)
    used = archive_bytes()
    print(f"archive currently {used / (1024**3):.2f} GB; "
          f"budget {args.budget_gb:.2f} GB", flush=True)

    if args.dry_run:
        for item in entries[:80]:
            print(f"  [{item['source']:15s}] [{item['topic']:16s}] "
                  f"{item['title'][:80]}", flush=True)
        print(f"{len(entries)} candidates; dry run only", flush=True)
        return 0

    budget = Budget(limit, used)
    failures: list[tuple[str, str]] = []
    completed = 0
    with ThreadPoolExecutor(max_workers=args.workers) as pool:
        futures = {
            pool.submit(download_item, item, budget, manifest,
                        args.max_file_mb): item
            for item in entries
        }
        for future in as_completed(futures):
            item = futures[future]
            completed += 1
            try:
                record = future.result()
                print(f"  ok  {record['slug'][:60]} "
                      f"({sum(f['bytes'] for f in record['files']) / 1048576:.1f} MB)",
                      flush=True)
            except Exception as error:  # noqa: BLE001
                failures.append((item["title"], str(error)))
                print(f"  !!  {item['title'][:60]}: {error}", flush=True)
            if completed % 10 == 0:
                print(f"  {completed}/{len(entries)} processed; "
                      f"{budget.used / (1024**3):.2f} GB used", flush=True)

    final = archive_bytes()
    SUMMARY.write_text(json.dumps({
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "budget_gb": args.budget_gb,
        "archive_bytes": final,
        "archive_gb": round(final / (1024**3), 2),
        "manifest_records": len(manifest.records),
        "attempted": len(entries),
        "failures": len(failures),
        "failure_details": failures[:50],
    }, indent=2) + "\n", encoding="utf-8")
    print(f"done: {len(entries) - len(failures)}/{len(entries)} items; "
          f"{final / (1024**3):.2f} GB on disk", flush=True)
    if failures:
        print(f"{len(failures)} failures (see {SUMMARY})", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
