#!/usr/bin/env python3
"""Download public-domain farm books into the offline archive.

Selections come from Project Gutenberg and Internet Archive. Only source
metadata is recorded: title, creator, date, subjects, licence and source URL.
No descriptions or summaries are generated by this tool.

    python3 tools/download_free_books.py --budget-gb 25 --dry-run
    python3 tools/download_free_books.py --budget-gb 25

The run is resumable and writes ``<archive>/books/sources_manifest.jsonl``.
It does not edit the site seed catalogue, so it is safe to run while another
process is working on the site.
"""
